#!/usr/bin/env python3
"""Render the ADK submission package of the agent from `agent/knobs.toml`.

    python tools/generate.py                      # -> build/submission/
    python tools/generate.py --zip                # also writes build/submission.zip

Inputs:  agent/knobs.toml, agent/prompt.md, skill/swe-coder/, tools/_budget.template.py and the packed engine
         build/swe_coder.txt (made by tools/build_engine.sh, or by tools/pack_engine.py from your own build).
Output:  agent.yaml, eval_config.yaml, configs/sampling.yaml, prompts/system.md and skills/swe-coder/.

Python 3.11+ (tomllib), standard library only. Every file is written with LF line endings. The header comments
of the generated files are fixed strings: they are part of the reference package that `--check` compares with.
"""

from __future__ import annotations

import argparse
import hashlib
import math
import re
import sys
import tomllib
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKILL = "swe-coder"
SCRIPTS = ["_boot.py", "boot.py", "debug.py", "patch.py", "probe.py", "verify.py", "view.py"]

# sha256 of the rendered files of the reference package. The engine asset is reported separately: its bytes
# depend on the Rust toolchain that built it.
REFERENCE = {
    "agent.yaml": "4f7ec6cf853d0c56d1d89ee3762aca3842f080897e688b8585311779fce5b8ef",
    "eval_config.yaml": "5d8f40a8463b9951deb352496a1600aecc3b9cedd72faa3d39dfc927e080dd40",
    "configs/sampling.yaml": "31ed5a232fd420f0019a0df402812e255fdbaedf992c54a05afae4cd74f1d5c2",
    "prompts/system.md": "2cb43bc3d81730508c464182cdf22c8b348e8e42b9b0206f3374305da7909160",
    "skills/swe-coder/SKILL.md": "6a68b395f1eda77fcaf27c3d42ad2886bce404bba5e93072b161d16d32aa4587",
    "skills/swe-coder/scripts/_budget.py": "c542489b4b3bd8c2ac70d6f6e85a6f55bcbe08a092592fffc6b125a4e128b121",
}
REFERENCE_ASSET = "ca497b4526df8f83d5ba61afb64da928295e2f3f0d2b83fb5d85d3d08e6c73e9"


def num(v: float) -> str:
    """8.0 -> '8', 5.5 -> '5.5' (the YAML the harness reads)."""
    return str(int(v)) if float(v).is_integer() else str(v)


def read(path: Path) -> str:
    return path.read_text(encoding="utf-8").replace("\r\n", "\n")


def render_agent_yaml(k: dict) -> str:
    a = k["agent"]
    lines = [
        f"# Generated by `swe gen` from submission/{k['meta']['version']}/knobs.toml. Do not edit.",
        "name: swe_agent",
        f"model: {a['model']}",
        "description: Resolves one repository issue with a minimal, verified source patch.",
        "instruction: !include prompts/system.md",
        "generate_content_config: !include configs/sampling.yaml",
    ]
    if a.get("adapter"):
        lines.append(f"adapter: {a['adapter']}")
    lines.append("tools:")
    lines += [f"  - {t}" for t in a["tools"]]
    lines.append("skills:")
    lines += [f"  - skills/{s}" for s in a["skills"]]
    return "\n".join(lines) + "\n"


def render_eval_config(k: dict) -> str:
    b = k["budget"]
    return (
        "# Generated by `swe gen`. The scorer reads only these four keys.\n"
        "evaluation:\n"
        f"  max_time_minutes: {num(b['max_time_minutes'])}\n"
        f"  max_tool_calls: {b['max_tool_calls']}\n"
        f"  max_turns: {b['max_turns']}\n"
        f"  timeout_seconds: {b['command_timeout_seconds']}\n"
    )


def render_sampling(k: dict) -> str:
    s = k["sampling"]
    return (
        "# Generated by `swe gen`. Do not edit.\n"
        f"temperature: {s['temperature']}\n"
        f"top_p: {s['top_p']}\n"
        f"presence_penalty: {s['presence_penalty']}\n"
        f"max_output_tokens: {s['max_output_tokens']}\n"
        "thinking_config:\n"
        f"  thinking_budget: {s['thinking_budget']}\n"
        f"  include_thoughts: {'true' if s['include_thoughts'] else 'false'}\n"
    )


def render_prompt(k: dict) -> str:
    b = k["budget"]
    # minutes the model plans for: half a minute of headroom before the harness limit
    agent_minutes = math.floor(max(b["max_time_minutes"] - 0.5, 1.0))
    text = read(ROOT / "agent" / "prompt.md")
    text = text.replace("{{agent_minutes}}", str(agent_minutes)).replace("{{max_tool_calls}}", str(b["max_tool_calls"]))
    left = re.findall(r"\{\{\w+\}\}", text)
    if left:
        sys.exit(f"agent/prompt.md has unknown placeholders: {sorted(set(left))}")
    return text


def render_skill_md(k: dict) -> str:
    """SKILL.md holds one section per call shape; keep the front matter and the section of `agent.call_shape`."""
    shape = "cmd" if k["agent"].get("call_shape") == "cmd" else "skill"
    text = read(ROOT / "skill" / SKILL / "SKILL.md")
    front = re.match(r"---\n.*?\n---\n", text, re.S)
    body = re.search(rf"<!--{shape}-->\n(.*?)<!--/{shape}-->", text, re.S)
    if not front or not body:
        sys.exit(f"skill/{SKILL}/SKILL.md: front matter or <!--{shape}--> section not found")
    return front.group(0) + "\n" + body.group(1)


def render_budget(k: dict) -> str:
    """`_budget.py` is what the skill scripts import. With the flat call shape the engine reads only MAX_TIME_S,
    MAX_TOOL_CALLS and HAS_SUBMIT (through the /tmp/coder wrapper that boot.py writes); the other constants of the
    template are used by the nested `run_skill_script` call shape."""
    b, a = k["budget"], k["agent"]
    text = read(ROOT / "tools" / "_budget.template.py")
    subs = {
        "MAX_TIME_S": str(int(b["max_time_minutes"] * 60)),
        "MAX_TOOL_CALLS": str(b["max_tool_calls"]),
        "HAS_SUBMIT": "True" if "submit_patch" in a["tools"] else "False",
        "CALL_SHAPE": f'"{a.get("call_shape", "skill")}"',
    }
    for key, val in subs.items():
        text, n = re.subn(rf"(?m)^{key} = .*$", f"{key} = {val}", text)
        if n != 1:
            sys.exit(f"tools/_budget.template.py: expected one `{key} = ...` line, found {n}")
    text = re.sub(r"submission/v[\d.]+/knobs\.toml", f"submission/{k['meta']['version']}/knobs.toml", text)
    return text


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--knobs", type=Path, default=ROOT / "agent" / "knobs.toml")
    ap.add_argument("--asset", type=Path, default=ROOT / "build" / "swe_coder.txt", help="packed engine binary")
    ap.add_argument("--out", type=Path, default=ROOT / "build" / "submission")
    ap.add_argument("--zip", action="store_true", help="also write <out>.zip")
    ap.add_argument("--check", action="store_true", help="compare the output with the reference package")
    args = ap.parse_args()

    k = tomllib.loads(read(args.knobs))
    if k["agent"]["skills"] != [SKILL]:
        sys.exit(f"this generator renders the single skill `{SKILL}`; knobs ask for {k['agent']['skills']}")
    if not args.asset.is_file():
        sys.exit(f"{args.asset} not found: build the engine first (tools/build_engine.sh, see README)")

    files: dict[str, bytes] = {
        "agent.yaml": render_agent_yaml(k).encode(),
        "eval_config.yaml": render_eval_config(k).encode(),
        "configs/sampling.yaml": render_sampling(k).encode(),
        "prompts/system.md": render_prompt(k).encode(),
        f"skills/{SKILL}/SKILL.md": render_skill_md(k).encode(),
        f"skills/{SKILL}/scripts/_budget.py": render_budget(k).encode(),
        f"skills/{SKILL}/assets/swe_coder.txt": args.asset.read_bytes().replace(b"\r\n", b"\n"),
    }
    for name in SCRIPTS:
        files[f"skills/{SKILL}/scripts/{name}"] = read(ROOT / "skill" / SKILL / "scripts" / name).encode()

    for rel, data in sorted(files.items()):
        dst = args.out / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_bytes(data)
        print(f"{sha(data)[:16]}  {len(data):>8}  {rel}")
    print(f"wrote {len(files)} files to {args.out}")

    if args.zip:
        zpath = args.out.with_suffix(".zip")
        with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
            for rel, data in sorted(files.items()):
                z.writestr(zipfile.ZipInfo(rel, date_time=(1980, 1, 1, 0, 0, 0)), data, zipfile.ZIP_DEFLATED)
        print(f"wrote {zpath} ({zpath.stat().st_size} bytes)")

    if args.check:
        bad = [rel for rel, want in REFERENCE.items() if sha(files[rel]) != want]
        for rel in bad:
            print(f"DIFFERS from the reference package: {rel}")
        asset_same = sha(files[f"skills/{SKILL}/assets/swe_coder.txt"]) == REFERENCE_ASSET
        print(
            "engine asset: identical to the reference one"
            if asset_same
            else "engine asset: differs from the reference one (expected when the Rust toolchain differs)"
        )
        if bad:
            return 1
        print(f"check ok: {len(REFERENCE)} generated files are byte-identical to the reference package")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
